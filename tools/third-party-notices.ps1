<#
.SYNOPSIS
  Regenerates THIRD-PARTY-NOTICES.md (ADR-0009).

.DESCRIPTION
  Rust: `cargo about generate` over the app's dependency graph (about.toml + about.hbs).
  UI: production dependencies from `pnpm licenses list --prod --json`, with each package's
  LICENSE file. Requires `cargo install --locked cargo-about --features cli`.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$root = Resolve-Path (Join-Path $PSScriptRoot '..')
$output = Join-Path $root 'THIRD-PARTY-NOTICES.md'

Push-Location $root
try {
    # cargo-about refuses PowerShell redirection (encoding); it writes the file itself.
    $rustFile = Join-Path ([System.IO.Path]::GetTempPath()) "clipvault-rust-notices-$PID.md"
    & cargo about generate --offline -m app/Cargo.toml -o $rustFile about.hbs
    if ($LASTEXITCODE -ne 0) { throw "cargo about failed with exit code $LASTEXITCODE" }
    $rust = [System.IO.File]::ReadAllText($rustFile)
    Remove-Item $rustFile

    $json = (& pnpm --dir ui licenses list --prod --json) -join "`n"
    if ($LASTEXITCODE -ne 0) { throw "pnpm licenses failed with exit code $LASTEXITCODE" }
    $byLicense = $json | ConvertFrom-Json -AsHashtable

    $ui = [System.Text.StringBuilder]::new()
    [void]$ui.AppendLine('## UI (npm packages bundled into the interface)')
    [void]$ui.AppendLine()
    $packages = foreach ($license in $byLicense.Keys) {
        foreach ($package in $byLicense[$license]) {
            [pscustomobject]@{
                Name     = $package.name
                Versions = $package.versions -join ', '
                License  = $license
                Homepage = $package.homepage
                Path     = $package.paths[0]
            }
        }
    }
    foreach ($package in $packages | Sort-Object Name) {
        [void]$ui.AppendLine("### $($package.Name) $($package.Versions)")
        [void]$ui.AppendLine()
        [void]$ui.AppendLine("License: $($package.License)" + $(if ($package.Homepage) { " · <$($package.Homepage)>" }))
        $file = Get-ChildItem $package.Path -File -ErrorAction SilentlyContinue |
            Where-Object { $_.Name -match '^(LICEN[CS]E|COPYING)' } |
            Select-Object -First 1
        if ($file) {
            [void]$ui.AppendLine()
            [void]$ui.AppendLine('```text')
            [void]$ui.AppendLine((Get-Content $file.FullName -Raw).TrimEnd())
            [void]$ui.AppendLine('```')
        }
        [void]$ui.AppendLine()
    }

    $header = @'
# Third-party notices · Avisos de terceiros

ClipVault includes the open-source software listed below. Each component is distributed under
its own license, reproduced here.

O ClipVault inclui os softwares de código aberto listados abaixo. Cada componente é distribuído
sob a própria licença, reproduzida aqui.

<!-- Generated by tools/third-party-notices.ps1 (ADR-0009). Do not edit by hand. -->

'@
    $text = ($header + $rust.TrimEnd() + "`n`n" + $ui.ToString().TrimEnd() + "`n") -replace "`r`n", "`n"
    [System.IO.File]::WriteAllText($output, $text, [System.Text.UTF8Encoding]::new($false))
    Write-Host "Wrote $output"
}
finally {
    Pop-Location
}
